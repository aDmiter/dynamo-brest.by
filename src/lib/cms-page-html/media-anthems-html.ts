import { escapeHtml } from '@/lib/html';
import { dividerHtml, sectionHtml, wrapCmsPageContent } from '@/lib/cms-page-html/helpers';

const SOUNDCLOUD_PLAYER_PARAMS =
  'color=%23003366&auto_play=false&hide_related=false&show_comments=true&show_user=true&show_reposts=false&show_teaser=true';

function soundcloudPlayerHtml(trackId: string): string {
  const src = `https://w.soundcloud.com/player/?url=https%3A//api.soundcloud.com/tracks/${trackId}&${SOUNDCLOUD_PLAYER_PARAMS}`;
  return `<div class="media-anthems__player">
<iframe class="media-anthems__player-iframe" title="SoundCloud" width="100%" height="166" scrolling="no" frameborder="no" allow="autoplay" src="${escapeHtml(src)}"></iframe>
</div>`;
}

function lyricsHtml(lines: string[]): string {
  const body = lines.map((line) => escapeHtml(line)).join('<br />');
  return `<div class="media-anthems__lyrics"><p class="transport-services__vehicle-desc">${body}</p></div>`;
}

function anthemSection(id: string, title: string, soundcloudTrackId: string, lines: string[]): string {
  return sectionHtml(
    id,
    title,
    `${soundcloudPlayerHtml(soundcloudTrackId)}<h3 class="transport-services__subsection-title">Текст гимна</h3>${lyricsHtml(lines)}`,
  );
}

